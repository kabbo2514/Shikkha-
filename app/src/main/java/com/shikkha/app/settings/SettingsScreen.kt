import kotlinx.coroutines.launch

@HiltViewModel
class SettingsViewModel @Inject constructor(
    private val settingsStore: SettingsStore,
) : ViewModel() {

    val shuffle: StateFlow<Boolean> = settingsStore.shuffleQuestions
        .stateIn(viewModelScope, SharingStarted.WhileSubscribed(5000), true)

    fun setShuffle(enabled: Boolean) {
        viewModelScope.launch { settingsStore.setShuffleQuestions(enabled) }
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SettingsScreen(
    onBack: () -> Unit,
    viewModel: SettingsViewModel = hiltViewModel(),
) {
    val shuffle by viewModel.shuffle.collectAsStateWithLifecycle()

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.settings_title)) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                },
            )
        },
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp),
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Column(Modifier.weight(1f)) {
                    Text(
                        stringResource(R.string.setting_shuffle),
                        style = MaterialTheme.typography.bodyLarge,
                    )
                }
                Switch(checked = shuffle, onCheckedChange = { viewModel.setShuffle(it) })
            }

            Spacer(Modifier.height(8.dp))
            Text(
                stringResource(R.string.setting_language_note),
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
    }
}
